"""T2: external-effect parity in disposable twin VMs (M8a).

T1 compares what each agent asks the host to do (recorded shims). T2 lets
the host do it: each side runs in its own throwaway QEMU VM, both booted
from one golden snapshot, and the comparison covers what changed on that
host -- files (path, type, mode, owner, sha256), the system and user
service managers (`systemctl show` for every unit that appeared or
changed), user lingering and the firewall -- plus every answer the agent
gave.

* The golden image is built once from the gpg-verified Ubuntu 24.04 cloud
  image (`python3 -m parity t2 golden`) and never changes afterwards; its
  sha256 is recorded with every capture. Background apt, snap and motd
  jobs are disabled in it so a twin changes only what the scenario does.
* Every twin boots a fresh copy-on-write overlay of the golden image,
  which is deleted when the scenario ends. Nothing outside the VM is
  touched: there is no shared Incus, Kubernetes, tunnel or deployment
  state, and the VMs reach only the public package mirrors over QEMU's
  user-mode NAT.
* The agent runs as `ubuntu` in a system transient unit, and the driver
  connects as root, so no login session keeps a user service manager
  alive: lingering is an effect under test.

Scenarios live in scenarios-t2/*.json (generated by t2_scenarios.py) so
the T1 runner never loads them. A scenario's "snapshot" steps name a
baseline; the compared observation is the delta against it.
"""
