GOLDEN_EXTRA = {"k3s": [agent.PROVIDER_BIN / "opute-provider-k3s"]}


# --- one twin -----------------------------------------------------------------------


class Twin:
    """One disposable VM: an overlay of the golden image, deleted on exit."""

    def __init__(self, label: str, binary: Path, run_dir: Path, golden: str = "base"):
        self.label, self.binary, self.run_dir = label, binary, run_dir
        self.image = WORK / GOLDEN_IMAGES[golden]
        self.memory_mb = MEMORY_MB if golden == "base" else INCUS_MEMORY_MB
        self.golden = golden
        self.disk = run_dir / f"{label}.qcow2"
        self.port = _free_port()
        self.process: subprocess.Popen | None = None
        self.record: dict = {}

    def __enter__(self) -> "Twin":
        self.run_dir.mkdir(parents=True, exist_ok=True)
        subprocess.run(["qemu-img", "create", "-q", "-f", "qcow2", "-F", "qcow2", "-b",
                        str(self.image), str(self.disk)], check=True)
        argv = _qemu(self.disk, WORK / "seed.img", self.port, self.run_dir / f"{self.label}-serial.log",
                     self.memory_mb)
        self.process = subprocess.Popen(argv, stdout=(self.run_dir / f"{self.label}-qemu.log").open("w"),
                                        stderr=subprocess.STDOUT)
        self.record = {"qemuArgv": argv, "booted": time.time()}
        _wait_ssh(self.port, self.process)
        ssh = _ssh_base(self.port)
        # systemd-fsckd serves the boot-time fsck and exits on its own about
        # 30s after going idle, which can land inside a scenario and show as
        # a unit change on one twin only. Wait for it to leave, never stop it.
        subprocess.run(ssh + ["systemctl is-system-running --wait >/dev/null 2>&1; "
                              "timeout 180 sh -c 'while systemctl is-active --quiet systemd-fsckd.service; "
                              "do sleep 1; done'; "
                              # incusd is socket-activated: started here, it has set up its
                              # bridge and firewall before the first baseline, not during it.
                              + ("incus admin waitready --timeout=180 && " if self.golden != "base" else "") +
                              "mkdir -p /opt/parity-t2/state /opt/parity-t2/instance && "
                              "chown -R ubuntu:ubuntu /opt/parity-t2"], check=True, capture_output=True)
        scp = ["scp", "-q"] + [a for a in _ssh_base(self.port)[1:-3] if a != "-p"] + ["-P", str(self.port)]
        subprocess.run(scp + [str(self.binary)] + [str(GUEST_DIR / f) for f in GUEST_FILES]
                       + [str(f) for f in GOLDEN_EXTRA.get(self.golden, [])]
                       + ["root@127.0.0.1:/opt/parity-t2/"], check=True)
        subprocess.run(ssh + ["mv /opt/parity-t2/" + shlex.quote(self.binary.name) + " /opt/parity-t2/agent && "
                              "chmod 0755 /opt/parity-t2/agent && chown ubuntu:ubuntu /opt/parity-t2/agent"],
                       check=True, capture_output=True)
        return self

    def run(self, program: dict, timeout: float = 7200) -> dict:
        done = subprocess.run(_ssh_base(self.port) + ["python3", "/opt/parity-t2/driver.py"],
                              input=json.dumps(program), capture_output=True, text=True, timeout=timeout)
        if done.returncode != 0:
            raise RuntimeError(f"driver failed ({done.returncode}): {done.stderr[-2000:]}")
        return json.loads(done.stdout)

    def __exit__(self, *exc: Any) -> None:
        if self.process and self.process.poll() is None:
            subprocess.run(_ssh_base(self.port) + ["poweroff"], capture_output=True, timeout=30)
            try:
                self.process.wait(timeout=60)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait()
        self.record["stopped"] = time.time()
        self.disk.unlink(missing_ok=True)


# --- observations -------------------------------------------------------------------


def _delta(before: dict, after: dict) -> dict:
    added = {k: v for k, v in after.items() if k not in before}
    removed = {k: v for k, v in before.items() if k not in after}
    changed = {k: {"before": before[k], "after": v} for k, v in after.items() if k in before and before[k] != v}
    return {key: value for key, value in (("added", added), ("removed", removed), ("changed", changed)) if value}


def effects(base: dict, current: dict) -> dict:
    """What changed on the host since `base`."""
    out: dict = {"files": _delta(base["files"], current["files"])}
    for scope in ("system", "user"):
        b, c = base[scope], current[scope]
        entry: dict = {}
        if b.get("running") != c.get("running"):
            entry["running"] = {"before": b.get("running"), "after": c.get("running")}
        for kind in ("unitFiles", "units"):
            # The harness's transient unit is the agent under test, not an effect of it.
            d = _delta({k: v for k, v in b.get(kind, {}).items() if k != AGENT_UNIT},
                       {k: v for k, v in c.get(kind, {}).items() if k != AGENT_UNIT})
            if d:
                entry[kind] = d
        if c.get("show"):
            entry["show"] = c["show"]
        out[scope] = entry
    if base["linger"] != current["linger"]:
        out["linger"] = {"before": base["linger"], "after": current["linger"]}
    fw = {}
    for name in ("nft", "iptables", "ip6tables"):
        if base["firewall"].get(name) != current["firewall"].get(name):
            fw[name] = {"before": base["firewall"].get(name), "after": current["firewall"].get(name)}
    out["firewall"] = fw
    b, c = base.get("kubernetes"), current.get("kubernetes")
    if b is not None or c is not None:
        b, c = b or {}, c or {}
        k8s = {kind: d for kind in ("objects", "images", "k1Files", "k1Units")
               if (d := _delta(b.get(kind, {}), c.get(kind, {})))}
        for key in ("listErrors", "registry"):
            if b.get(key) != c.get(key):
                k8s[key] = {"before": b.get(key), "after": c.get(key)}
        out["kubernetes"] = k8s
    b, c = base.get("incus"), current.get("incus")
    if b is not None or c is not None:
        out["incus"] = {kind: d for kind in sorted(set(b or {}) | set(c or {}))
                        if (d := _delta((b or {}).get(kind, {}), (c or {}).get(kind, {})))}
    return out


def harness_errors(obs: dict) -> dict:
    """Steps that did not run as written: a scenario with any is not evidence.

    An unknown tool name, an unbound capture (a call expected to start a task
    answered without one) or a driver exception would otherwise make both twins
    agree on nothing having happened.
    """
    out = {}
    for label, result in obs["steps"].items():
        if not isinstance(result, dict):
            continue
        if "unbound" in result or "exception" in result:
            out[label] = result
            continue
        error = (result.get("body") or {}).get("error") if isinstance(result.get("body"), dict) else None
        if isinstance(error, dict) and str(error.get("message", "")).startswith("unknown tool"):
            out[label] = error
    return out


def unexpected_effects(obs: dict, scenario: dict) -> dict:
    """Snapshot steps marked expectEmpty whose delta is not empty.

    Equality with the other twin is not enough for these: an admission-rejected
    call must leave the host exactly as it was (M8 validation 4).
    """
    out = {}
    for step in scenario["steps"]:
        expect = step.get("snapshot", {}).get("expectEmpty")
        if not expect:
            continue
        eff = obs["steps"].get(step["as"])
        if not isinstance(eff, dict) or "files" not in eff:
            out[step["as"]] = {"missing": True}
            continue
        # {"except": [dir...]}: file changes under these directories are the
        # declared, expected bookkeeping of admitted calls (the admission
        # coordinator's own ledger); everything else must stay unchanged.
        excepted = expect.get("except", []) if isinstance(expect, dict) else []
        eff = dict(eff, files={
            kind: {path: v for path, v in entries.items()
                   if not any(path == d or path.startswith(d + "/") for d in excepted)}
            for kind, entries in eff["files"].items()})
        eff["files"] = {k: v for k, v in eff["files"].items() if v}
        nonempty = {k: v for k, v in eff.items() if v}
        if nonempty:
            out[step["as"]] = nonempty
    return out


# Incus names each container's host-side veth and each VM's tap device
# randomly, and systemd lists a device unit per name (in unit names and
# descriptions). The names are replaced by their order within the snapshot;
# every such unit is otherwise alike.
VETH_UNIT = re.compile(r"^sys-(?:devices-virtual-net|subsystem-net-devices)-((?:veth|tap)[0-9a-f]{8})\.device$")


def _stable_device_names(snapshot: dict) -> dict:
    out = dict(snapshot)
    for scope in ("system", "user"):
        manager = snapshot.get(scope)
        if not isinstance(manager, dict):
            continue
        veths = sorted({m.group(1) for kind in ("unitFiles", "units", "show") for u in manager.get(kind, {})
                        if (m := VETH_UNIT.match(u))})
        if veths:
            ids = {v: f"{v[:-8]}#{i}" for i, v in enumerate(veths)}
            text = re.sub(r"\b(" + "|".join(veths) + r")\b", lambda m: ids[m.group(1)], json.dumps(manager))
            out[scope] = json.loads(text)
    return out


def observation(raw: dict, scenario: dict) -> dict:
    """The compared observation: answers as given, snapshots as deltas."""
    steps = {}
    snapshots = {}
    for step in scenario["steps"]:
        label = step["as"]
        result = raw["steps"].get(label)
        if "snapshot" in step and isinstance(result, dict) and "snapshot" in result:
            snapshots[label] = _stable_device_names(result["snapshot"])
            base = step["snapshot"].get("baseline")
            steps[label] = effects(snapshots[base], snapshots[label]) if base in snapshots else {"baseline": True}
        else:
            steps[label] = result
    return {"steps": steps}


# --- running scenarios --------------------------------------------------------------


def load_scenarios(ids: list[str] | None = None) -> list[dict]:
    scenarios = []
    for path in sorted(SCENARIO_DIR.glob("*.json")):
        for scenario in json.loads(path.read_text()):
            scenario["_file"] = str(path.relative_to(REPO_ROOT))
            scenarios.append(scenario)
    if ids:
        wanted = set(ids)
        scenarios = [s for s in scenarios if s["id"] in wanted]
        missing = wanted - {s["id"] for s in scenarios}
        if missing:
            raise ValueError(f"unknown T2 scenarios: {sorted(missing)}")
    return scenarios


def _execute(impl: agent.Impl, scenario: dict, side: str, run_dir: Path) -> dict:
    program = {"agent": {"env": AGENT_ENV}, "steps": scenario["steps"]}
    try:
        with Twin(side, impl.binary, run_dir, scenario.get("golden", "base")) as twin:
            raw = twin.run(program)
            twin_record = dict(twin.record)
        return {"raw": raw, "twin": twin_record, "error": None}
    except Exception as e:  # recorded as an execution failure, never relabelled
        return {"raw": {"steps": {}}, "twin": {}, "error": f"{type(e).__name__}: {e}"}


def judge(scenario: dict, out_l: dict, out_r: dict, left_label: str, right_label: str) -> dict:
    """Compare two twins' executions of one scenario (also used by t2_verify)."""
    spec = scenario.get("compare", {})
    obs_l = observation(out_l["raw"], scenario)
    obs_r = observation(out_r["raw"], scenario)
    if out_l["error"]:
        obs_l["_executionError"] = out_l["error"]
    if out_r["error"]:
        obs_r["_executionError"] = out_r["error"]
    norm_l, viol_l = canon.normalize(obs_l, spec, out_l["raw"].get("variables", {}))
    norm_r, viol_r = canon.normalize(obs_r, spec, out_r["raw"].get("variables", {}))
    divergences: list = []
    if left_label.startswith("rust") != right_label.startswith("rust"):
        norm_l, norm_r, divergences = canon.apply_divergences(
            norm_l, norm_r, spec.get("divergences", []), canon.load_divergences(TOOLS_DIR / "divergences.json"),
            rust_side="b" if right_label.startswith("rust") else "a")
    return {"observation": {"a": obs_l, "b": obs_r},
            "diff": canon.diff(norm_l, norm_r), "maskViolations": {"a": viol_l, "b": viol_r},
            "unexpectedEffects": {"a": unexpected_effects(obs_l, scenario),
                                  "b": unexpected_effects(obs_r, scenario)},
            "harnessErrors": {"a": harness_errors(obs_l), "b": harness_errors(obs_r)},
            "divergences": divergences}


def failed(outcome: dict, errors: dict) -> bool:
    return bool(outcome["diff"] or any(outcome["maskViolations"].values())
                or any(outcome["unexpectedEffects"].values())
                or any(outcome["harnessErrors"].values())
                or errors["a"] or errors["b"]
                or any(d["stale"] for d in outcome["divergences"]))


def compare_once(left: agent.Impl, right: agent.Impl, scenario: dict, run_dir: Path) -> dict:
    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
        fut_l = pool.submit(_execute, left, scenario, "a", run_dir)
        fut_r = pool.submit(_execute, right, scenario, "b", run_dir)
        out_l, out_r = fut_l.result(), fut_r.result()
    return {"a": out_l, "b": out_r, **judge(scenario, out_l, out_r, left.label, right.label)}


def _store_snapshots(record: dict, store: Path) -> dict:
    """Move each raw snapshot into a content-addressed store, by sha256.

    Snapshots dominate a capture and repeat across twins and iterations; the
    record keeps every other raw byte and names each snapshot by its hash,
    so `observation` can be recomputed from the receipts alone.
    """
    record = json.loads(json.dumps(record))
    for label, result in (record.get("raw", {}).get("steps") or {}).items():
        if isinstance(result, dict) and isinstance(result.get("snapshot"), dict):
            data = json.dumps(result["snapshot"], sort_keys=True, separators=(",", ":")).encode()
            digest = hashlib.sha256(data).hexdigest()
            path = store / f"{digest}.json.gz"
            if not path.exists():
                store.mkdir(parents=True, exist_ok=True)
                tmp = path.with_name(f".{digest}.{os.getpid()}.{threading.get_ident()}.tmp")
                tmp.write_bytes(gzip.compress(data, mtime=0))
                os.replace(tmp, path)
            result["snapshot"] = {"sha256": digest}
    return record


def load_snapshot(store: Path, digest: str) -> dict:
    data = gzip.decompress((store / f"{digest}.json.gz").read_bytes())
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError(f"snapshot {digest} does not match its content")
    return json.loads(data)


def _gz(data: Any) -> bytes:
    return gzip.compress(json.dumps(data, sort_keys=True).encode(), mtime=0)


def run_suite(left: agent.Impl, right: agent.Impl, out_dir: Path, ids: list[str] | None = None,
              repeat: int = 1, workers: int = 1) -> dict:
    golden = golden_record()
    scenarios_all = load_scenarios(ids)
    incus = incus_golden_record() if any(s.get("golden") == "incus" for s in scenarios_all) else None
    k3s = k3s_golden_record() if any(s.get("golden") == "k3s" for s in scenarios_all) else None
    # Hashed before the first twin boots: these are the bytes every twin of
    # this run receives (the harness is never edited mid-capture).
    guest_hashes = {name: sha256_file(GUEST_DIR / name) for name in GUEST_FILES}
    harness_hash = sha256_file(Path(__file__))
    scenario_hashes = {str(p.relative_to(REPO_ROOT)): sha256_file(p) for p in sorted(SCENARIO_DIR.glob("*.json"))}
    binaries = {"left": left.sha256(), "right": right.sha256()}
    scenarios = scenarios_all
    out_dir.mkdir(parents=True, exist_ok=True)
    # Workers bound how many twin pairs run at once; the memory budget also
    # does, since a nested-Incus pair needs three times a base pair.
    budget = {"free": MEMORY_BUDGET_MB}
    budget_cv = threading.Condition()

    def pair_memory(scenario: dict) -> int:
        return 2 * (MEMORY_MB if scenario.get("golden", "base") == "base" else INCUS_MEMORY_MB)

    def run_iteration(scenario: dict, i: int) -> dict:
        need = min(pair_memory(scenario), MEMORY_BUDGET_MB)  # one pair always runs
        with budget_cv:
            budget_cv.wait_for(lambda: budget["free"] >= need)
            budget["free"] -= need
        try:
            return run_iteration_admitted(scenario, i)
        finally:
            with budget_cv:
                budget["free"] += need
                budget_cv.notify_all()

    def run_iteration_admitted(scenario: dict, i: int) -> dict:
        # Every (scenario, iteration) is independent: each runs in its own
        # pair of disposable VMs booted from the golden image, so they may
        # run concurrently. Receipts are written per iteration.
        sdir = out_dir / "scenarios" / scenario["id"]
        sdir.mkdir(parents=True, exist_ok=True)
        outcome = compare_once(left, right, scenario, out_dir / "runs" / scenario["id"] / str(i))
        bad = failed(outcome, {"a": outcome["a"]["error"], "b": outcome["b"]["error"]})
        iteration = {"iteration": i, "pass": not bad, "diffCount": len(outcome["diff"])}
        store = out_dir / "snapshots"
        for side, label in (("a", left.label), ("b", right.label)):
            (sdir / f"{side}{i}.json.gz").write_bytes(_gz(_store_snapshots(
                {"label": label, **outcome[side], "observation": outcome["observation"][side]}, store)))
        (sdir / f"diff{i}.json").write_text(json.dumps({
            "diff": outcome["diff"], "maskViolations": outcome["maskViolations"],
            "unexpectedEffects": outcome["unexpectedEffects"], "harnessErrors": outcome["harnessErrors"],
            "divergences": outcome["divergences"],
            "errors": {"a": outcome["a"]["error"], "b": outcome["b"]["error"]}}, indent=1, sort_keys=True) + "\n")
        iteration["receipts"] = {name: sha256_file(sdir / name)
                                 for name in (f"a{i}.json.gz", f"b{i}.json.gz", f"diff{i}.json")}
        print(f"{'pass' if not bad else 'FAIL':4}  {scenario['id']}#{i}", flush=True)
        return iteration

    # Slowest scenarios (largest declared task timeouts) first, so they do not start last.
    order = sorted(scenarios, key=lambda s: -sum(st.get("mcp", {}).get("timeout", 0) for st in s["steps"]))
    with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, workers)) as pool:
        futures = {(s["id"], i): pool.submit(run_iteration, s, i) for s in order for i in range(repeat)}
        done = {key: fut.result() for key, fut in futures.items()}
    results = {}
    for scenario in scenarios:
        iterations = [done[(scenario["id"], i)] for i in range(repeat)]
        status = "pass" if all(it["pass"] for it in iterations) else "fail"
        results[scenario["id"]] = {"status": status, "iterations": iterations, "file": scenario["_file"]}
        print(f"{status:4}  {scenario['id']}  ({repeat} iterations)", flush=True)
    changed = (binaries != {"left": left.sha256(), "right": right.sha256()}
               or guest_hashes != {name: sha256_file(GUEST_DIR / name) for name in GUEST_FILES}
               or harness_hash != sha256_file(Path(__file__))
               or scenario_hashes != {str(p.relative_to(REPO_ROOT)): sha256_file(p)
                                      for p in sorted(SCENARIO_DIR.glob("*.json"))})
    summary = {
        "tier": "T2", "left": {"label": left.label, "sha256": binaries["left"]},
        "right": {"label": right.label, "sha256": binaries["right"]}, "changedDuringRun": changed,
        "workers": workers,
        "golden": {k: golden[k] for k in ("goldenSha256", "baseImageSha256", "baseImageSource", "seedSha256")},
        **({"incusGolden": {k: incus[k] for k in ("goldenSha256", "baseGoldenSha256")}} if incus else {}),
        **({"k3sGolden": {"goldenSha256": k3s["goldenSha256"], "incusGoldenSha256": k3s["incusGoldenSha256"],
                          "providerSha256": {p.name: sha256_file(p) for p in GOLDEN_EXTRA["k3s"]}}}
           if k3s else {}),
        "guestSha256": guest_hashes, "harnessSha256": harness_hash, "scenarioSha256": scenario_hashes,
        "repeat": repeat, "scenarios": results,
    }
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=1, sort_keys=True) + "\n")
    passed = sum(1 for r in results.values() if r["status"] == "pass")
    print(f"{passed}/{len(results)} T2 scenarios pass")
    return summary
