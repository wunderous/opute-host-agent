#!/usr/bin/env python3
"""Generate Go 1.25.4 printable-rune data for exact strconv.Quote diagnostics."""
from pathlib import Path
import hashlib
import re
root=Path(__file__).resolve().parents[2]
source=root/'.parity/setup/go/src/strconv/isprint.go'
assert (root/'.parity/setup/go/VERSION').read_text().splitlines()[0]=='go1.25.4'
text=source.read_text()
output=['// Copyright 2013 The Go Authors. All rights reserved.', '// SPDX-License-Identifier: BSD-3-Clause', '// See licenses/Go-BSD.txt.', '// Generated by tools/parity/generate_go_isprint.py; DO NOT EDIT.',f'// Go 1.25.4 strconv/isprint.go SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}','']
for go,rust in [('isPrint16','PRINT16'),('isNotPrint16','EXCEPT16'),('isPrint32','PRINT32'),('isNotPrint32','EXCEPT32')]:
    body=re.search(r'var '+go+r' = \[\]uint\d+\{(.*?)\n\}',text,re.S).group(1)
    body=re.sub(r'//[^\n]*','',body)
    values=[int(v,16) for v in re.findall(r'0x[0-9a-fA-F]+',body)]
    output.extend(['#[rustfmt::skip]',f'const {rust}: &[u32] = &['])
    output.extend('    '+', '.join(f'0x{v:04x}' for v in values[i:i+8])+',' for i in range(0,len(values),8))
    output.extend(['];',''])
output.extend(['pub(super) fn is_print(c: char) -> bool {','    let r = c as u32;','    let (ranges, exceptions, value) = if r < 0x10000 {','        (PRINT16, EXCEPT16, r)','    } else {','        (PRINT32, EXCEPT32, r - 0x10000)','    };','    let i = ranges.partition_point(|bound| *bound < r);','    i < ranges.len()', '        && ranges[i & !1] <= r', '        && r <= ranges[i | 1]','        && (r >= 0x20000 || exceptions.binary_search(&value).is_err())','}',''])
(root/'crates/host-agent/src/goerr/printable.rs').write_text('\n'.join(output))
