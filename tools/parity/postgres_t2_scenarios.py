#!/usr/bin/env python3
"""Generate scenarios-t2/postgres-domain.json: the M8e postgres-domain T2 matrix.

Run from tools/parity: python3 postgres_t2_scenarios.py

The service scenarios boot their twins from the PostgreSQL golden (`python3
-m parity t2 golden-postgres`): the k3s golden plus the CloudNativePG
operator (pinned chart, Go's values) and Go's operand image, preloaded by
digest. The pinned Go k3s provider is installed exactly as in the
cluster-domain T2 matrix, and every kubectl call of the domain goes through
it. The relay's loopback forward is a real Incus proxy device on k1, and
the relay and the SQL connector are real host TCP relays in the twin.

A harness-owned client checks the data path: psql in the primary (as its
own postgres user) writes a row before the second reconcile and reads it
back after, and a probe on the twin's loopback sends the relay's token line
and a PostgreSQL SSLRequest through the connector and the relay, recording
the server's one-byte answer. Go's standalone tools (install_postgresql,
run_sql, delete_postgresql) declare no resource binding, so they only
refuse (T1 postgres-domain.standalone); the data written here is the
harness's.

The SQLite scenario runs on the base golden: databases are host files.

Nothing outside the twin is touched: no shared Incus, Kubernetes, registry,
tunnel or deployment state, and no real database.
"""
import json
import sys

import cluster_t2_scenarios as ct
import t2_scenarios as hd

SNAP, STOP, call, task_call, shell = hd.snap, hd.STOP, hd.call, hd.task_call, hd.shell
K1 = ct.K1
PG = "internal/domain/postgres/"
DISPATCH = "internal/tools/dispatch_postgres.go"
RELAY_DIR = "/home/ubuntu/.opute/relays"
SQLITE_ROOT = "/home/ubuntu/.opute/databases"
ENV = {"OPUTE_HOST_AGENT_RELAY_DIR": RELAY_DIR, "OPUTE_HOST_AGENT_SQLITE_ROOT": SQLITE_ROOT}
TOKEN = "parity-relay-token-0123456789abcdef"
RELAY_PORT, CONNECTOR_PORT = 15433, 15432
SERVICE = {"uri": K1, "clusterName": "pg", "namespace": "platform", "databases": ["app", "ledger"],
           "consumerSecretName": "pg-consumer", "consumerSecretLabel": "opute.io/pg-consumer",
           "serviceOwner": "app", "servicePartOf": "opute-platform",
           "consumerDatabaseKeys": {"app": "DATABASE_URL", "ledger": "LEDGER_URL"}}
RELAY = {"sessionId": "parity-session", "relayToken": TOKEN}
RELAYED = {**SERVICE, "relayDeviceName": "opute-pg-rw",
           "localRelay": {**RELAY, "listenPort": RELAY_PORT, "persistent": True}}

# The operator restarts with k3s when a twin boots: wait for it (and its
# webhook) before the baseline, compared by exit status only.
CNPG_READY = shell("cnpgReady", ["sh", "-c",
                                 "(incus exec k1 -- k3s kubectl -n cnpg-system wait --for=condition=Available "
                                 "deployment --all --timeout=600s && timeout 600 sh -c 'until incus exec k1 -- k3s "
                                 "kubectl -n cnpg-system get endpoints cnpg-webhook-service -o "
                                 "jsonpath={.subsets[0].addresses[0].ip} | grep -q .; do sleep 2; done') >/dev/null"])


def psql(as_, sql):
    """The harness's own client: psql in the primary as its postgres user."""
    return shell(as_, ["incus", "exec", "k1", "--", "k3s", "kubectl", "-n", "platform", "exec", "pg-1", "-c",
                       "postgres", "--", "psql", "-d", "app", "-Atqc", sql])


# Connect to a loopback port, send a token line (when given) and a
# PostgreSQL SSLRequest, and print the server's one-byte answer: 'S' or 'N'
# from PostgreSQL, "closed" when the connection ends without an answer, or
# the error's name when nothing listens. A relay that refuses a token closes
# with the SSLRequest possibly still unread, so the client sees a clean end
# of stream or a reset by timing alone: both are "closed" (M8e round 2).
PROBE = ("import socket,sys\n"
         "try:\n"
         "    s=socket.create_connection(('127.0.0.1',int(sys.argv[1])),timeout=20)\n"
         "except OSError as e:\n"
         "    print(type(e).__name__); sys.exit()\n"
         "token=sys.argv[2] if len(sys.argv)>2 else ''\n"
         "try:\n"
         "    s.sendall((token+'\\n').encode() if token else b'')\n"
         "    s.sendall(bytes([0,0,0,8,4,210,22,47]))\n"
         "    answer=s.recv(1)\n"
         "    print(answer.decode() if answer else 'closed')\n"
         "except (ConnectionResetError, BrokenPipeError):\n"
         "    print('closed')\n")


def probe(as_, port, token=None):
    return shell(as_, ["python3", "-c", PROBE, str(port)] + ([token] if token else []), user="ubuntu")


SERVER_ASSIGNED = "assigned in this twin's k1 (uid, ClusterIP or loopback port)"
GENERATED = "generated by CloudNativePG or derived from its generated password in this twin"
# The relay's persisted state: sha256("parity-session").json.
RELAY_STATE = RELAY_DIR + "/postgresql-service-relays/8eaa817b4b470cce148263feea16807159de9d6599560e915aa5c8ae8c0fc2a8.json"
SECRETS = ["secrets/platform/pg-" + name for name in ("app", "ca", "replication", "server", "consumer")]


def objects(*rest, key="*"):
    """Every way a projected object shows in a delta: added, removed, or changed."""
    base = ["steps", "*", "kubernetes", "objects"]
    return [base + ["added", key, *rest], base + ["removed", key, *rest],
            base + ["changed", key, "before", *rest], base + ["changed", key, "after", *rest]]


MASKS = [
    *[{"path": p, "type": "uuid", "reason": SERVER_ASSIGNED, "optional": True}
      for p in objects("metadata", "ownerReferences", "*", "uid")],
    # Secret values (projected by sha256): CNPG's generated credentials and
    # certificates, and the consumer Secret's URLs built from them.
    *[{"path": p, "type": "hex", "reason": GENERATED, "optional": True}
      for secret in SECRETS for p in objects("data", "*", key=secret)],
    # The proxy device Go adds on k1: the Service's ClusterIP and a free
    # loopback port, both this twin's.
    *[{"path": ["steps", "*", "incus", "instances", "changed", "k1", side, "devices", "opute-pg-rw", key],
       "type": "string", "reason": SERVER_ASSIGNED, "optional": True}
      for side in ("before", "after") for key in ("connect", "listen")],
    # The relay's persisted state names that loopback port.
    *[{"path": ["steps", "*", "files", change, RELAY_STATE, "sha256"], "type": "hex",
       "reason": "the relay state file names this twin's loopback forward port", "optional": True}
      for change in ("added", "removed")],
    # The consumer Secret is applied with kubectl apply, whose annotation
    # (projected by sha256) carries the generated URLs.
    *[{"path": p, "type": "hex", "reason": GENERATED, "optional": True}
      for p in objects("metadata", "annotations", "kubectl.kubernetes.io/last-applied-configuration",
                       key="secrets/platform/pg-consumer")],
    # The harness's own psql client runs through kubectl exec, whose
    # websocket client may log "Unknown stream id" on stderr by timing (M8f
    # round 2). Its exit status and stdout stay compared.
    *[{"path": ["steps", as_, "stderr"], "type": "string", "optional": True,
       "reason": "kubectl exec's websocket client logs stream warnings by timing"} for as_ in ("write", "read")],
    # A claim marked for deletion, at this twin's time.
    *[{"path": p, "type": "rfc3339", "reason": "when k1's API server marked the claim for deletion",
       "optional": True} for p in objects("metadata", "deletionTimestamp")],
    # Results that carry the forward's port or the Service's address.
    *[{"path": ["steps", label, "body", "result", "structuredContent", "localRelay", "targetPort"],
       "type": "int", "reason": SERVER_ASSIGNED, "optional": True} for label in ("relay", "relayAgain")],
]


def scenario(id_, steps, anchors, residue, masks=(), rejected_only=False):
    out = ct.scenario(id_, steps, anchors, residue, masks=list(masks), rejected_only=rejected_only)
    out["id"] = "t2.postgres-domain." + id_
    out["owner"] = "postgres"
    out["golden"] = "postgres"
    out["commands"] = [] if rejected_only else ["incus"]
    return out


def setup():
    steps = ct.setup(**ENV)
    return [*steps[:-3], CNPG_READY, *steps[-3:]]


SERVICE_ANCHORS = [PG + f for f in ("platform_postgres.go", "platform_postgres_storage.go",
                                    "generic_postgresql_service.go", "platform_postgres_relay.go",
                                    "sql_connector.go")] + ["internal/tcprelay/tcprelay.go", DISPATCH] + ct.DOMAIN

cases = [
    # The service from nothing on an installed operator: the Cluster, its
    # databases and the consumer Secret; the relay and the connector carry
    # a client's bytes to PostgreSQL; a second reconcile keeps the data; the
    # relay is released only with its token; removal retains, then deletes.
    scenario("service.lifecycle", [
        *setup(), SNAP("baseline"),
        task_call("reconcile", "reconcile_postgresql_service", SERVICE, timeout=1500),
        SNAP("reconciled", "baseline"),
        psql("write", "CREATE TABLE parity_kept(note text); INSERT INTO parity_kept VALUES ('written before reconcile')"),
        call("relay", "get_postgresql_service_status", RELAYED),
        probe("relayProbe", RELAY_PORT, TOKEN),
        probe("relayWrongToken", RELAY_PORT, "not-the-relay-token-0123456789abcdef"),
        call("connector", "ensure_sql_connector", {"databaseId": "pg", "targetHost": "127.0.0.1",
                                                    "targetPort": RELAY_PORT, "listenHost": "127.0.0.1",
                                                    "listenPort": CONNECTOR_PORT}),
        probe("connectorProbe", CONNECTOR_PORT, TOKEN),
        SNAP("relayed", "reconciled"),
        task_call("reconcileAgain", "reconcile_postgresql_service", SERVICE, timeout=1500),
        psql("read", "SELECT note FROM parity_kept"),
        call("relayAgain", "get_postgresql_service_status", RELAYED),
        SNAP("reconciledAgain", "relayed"),
        call("releaseWrong", "release_postgresql_service_relay",
             {**RELAY, "relayToken": "not-the-relay-token-0123456789abcdef"}),
        call("release", "release_postgresql_service_relay", RELAY),
        call("connectorRelease", "release_sql_connector", {"databaseId": "pg", "force": True}),
        probe("connectorAfterRelease", CONNECTOR_PORT, TOKEN),
        SNAP("released", "reconciledAgain"),
        task_call("retain", "remove_postgresql_service", {**SERVICE, "confirm": True, "retentionPolicy": "retain"},
                  timeout=900),
        SNAP("retained", "released"),
        task_call("delete", "remove_postgresql_service", {**SERVICE, "confirm": True, "retentionPolicy": "delete"},
                  timeout=900),
        STOP, SNAP("teardown", "baseline"),
    ], SERVICE_ANCHORS,
        "The platform namespace stays. The HelmChart the steady reconcile applied stays (inert: the golden's helm "
        "controller is disabled). The Incus proxy device on k1 stays (removal does not remove it), and the relay "
        "state directory stays empty.",
        masks=MASKS),
]

# SQLite databases are host files: the base golden.
sqlite = hd.scenario("sqlite.lifecycle", [
    {"as": "serve", "serve": {"env": ENV}}, SNAP("baseline"),
    call("ensure", "ensure_sqlite_database", {"consumerId": "consumer-a", "databaseName": "main"}),
    call("again", "ensure_sqlite_database", {"consumerId": "consumer-a", "databaseName": "main"}),
    call("status", "get_sqlite_database_status", {"consumerId": "consumer-a", "databaseName": "main"}),
    SNAP("created", "baseline"),
    shell("journal", ["python3", "-c", "import sqlite3,sys; c=sqlite3.connect(sys.argv[1]); "
                                       "print(c.execute('PRAGMA journal_mode').fetchone()[0])",
                      SQLITE_ROOT + "/consumer-a/main.sqlite"], user="ubuntu"),
    call("unconfirmed", "remove_sqlite_database", {"consumerId": "consumer-a", "databaseName": "main"}),
    call("remove", "remove_sqlite_database", {"consumerId": "consumer-a", "databaseName": "main", "confirm": True}),
    STOP, SNAP("teardown", "baseline"),
], [PG + "sqlite_database.go", DISPATCH, "internal/config/config.go"],
    "The SQLite root and the consumer directory stay (0700); the database and its WAL files are removed.")
sqlite["id"] = "t2.postgres-domain.sqlite.lifecycle"
sqlite["owner"] = "postgres"
cases.append(sqlite)

# Every M4-rejected postgres call, with effectful arguments aimed at k1, the
# twin's loopback and its files, leaves the twin unchanged.
REJECTED = [
    ("delete_postgresql", {"vmName": "k1", "uri": K1}),
    ("ensure_sql_connector", {"databaseId": "rejected", "targetHost": "127.0.0.1", "targetPort": 9,
                              "listenPort": CONNECTOR_PORT}),
    ("ensure_sqlite_database", {"consumerId": "rejected", "databaseName": "main"}),
    ("install_postgresql", {"vmName": "k1", "uri": K1}),
    ("reconcile_postgresql_service", SERVICE),
    ("release_postgresql_service_relay", RELAY),
    ("release_sql_connector", {"databaseId": "rejected", "force": True}),
    ("remove_postgresql_service", {**SERVICE, "confirm": True}),
    ("remove_sqlite_database", {"consumerId": "rejected", "databaseName": "main", "confirm": True}),
    ("run_sql", {"vmName": "k1", "uri": K1, "sql": "DROP DATABASE app"}),
]
PG_TOOLS = {t["tool"] for t in json.load(open("../../baseline/inventory/postgres-domain.json"))["tools"]}
GATED = hd.M4_GATED & PG_TOOLS
REJECTED = [r for r in REJECTED if r[0] in GATED]
assert GATED == {n for n, _ in REJECTED}, sorted(GATED ^ {n for n, _ in REJECTED})


def rejected(prefix, meta=None):
    out = []
    for name, args in REJECTED:
        step = call(prefix + "." + name, name, args)
        if meta:
            step["mcp"]["meta"] = meta
        out.append(step)
    return out


def wrong_binding():
    defaults = dict(REJECTED)
    out = []
    for i, (name, args) in enumerate(b for b in hd.M4_BINDING if b[0] in PG_TOOLS):
        merged = {k: v for k, v in defaults.get(name, {}).items() if k != "uri"}
        merged.update(args)
        out.append(call(f"wrongBinding.{name}.{i}", name, merged))
    return out


def empty(as_):
    return {"as": as_, "snapshot": {"baseline": "baseline", "expectEmpty": True}}


cases.append(scenario("admission.rejected-no-effect", [
    *setup(), {"as": "stopInstall", "stop": {}},
    {"as": "serveClosed", "serve": {"env": ENV, "unset": ["OPUTE_STANDALONE_ALLOW_MUTATIONS"]}},
    SNAP("baseline"),
    rejected("gateClosed"),
    empty("afterGateClosed"),
    {"as": "stopClosed", "stop": {}},
    {"as": "serveOpen", "serve": {"env": ENV}},
    rejected("staleRevision", meta={"catalogRevision": "sha256:0000"}),
    wrong_binding(),
    empty("afterOpen"),
    STOP, empty("teardown"),
], hd.ADMISSION + ["internal/domain/postgres"],
    "None: the provider is installed before the baseline, and every rejected call is refused before it reaches "
    "k1, the twin's loopback or its files.", rejected_only=True))

if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "scenarios-t2/postgres-domain.json"
    with open(out, "w") as f:
        json.dump(cases, f, indent=1)
        f.write("\n")
    print(f"wrote {len(cases)} T2 scenarios to {out}")
